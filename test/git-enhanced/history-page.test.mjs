// The History page: commits with lanes, ↑ / ↓, a commit's details, files and diff, the search, All
// branches, reloading when the refs move, the commit menu's actions, the tab, Load more, keys.
import { test } from "node:test";
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { state, mount, overlay, drawWith, renderNow, draw, byId, lists, renderRows, handler, press, texts, walk, settle, makeCx, at, load } from "./render/load.mjs";
import { tempDir } from "./tmp.mjs";

const { KEY } = await load("id.js");
const sh = (cwd, ...a) => execFileSync("git", a, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
const cfg = (d) => { sh(d, "config", "user.name", "Tess"); sh(d, "config", "user.email", "tess@x"); sh(d, "config", "core.hooksPath", "/dev/null"); };
const commit = (dir, file, text, msg) => { writeFileSync(join(dir, file), text); sh(dir, "add", "-A"); sh(dir, "commit", "-qm", msg); return sh(dir, "rev-parse", "HEAD").trim(); };
export function historyRepos() {
  const base = tempDir("git-enhanced-history-");
  sh(base, "init", "-q", "--bare", "-b", "main", "remote.git");
  sh(base, "clone", "-q", "remote.git", "a"); const A = join(base, "a"); cfg(A);
  const first = commit(A, "f.txt", "one\n", "First");
  sh(A, "push", "-q", "-u", "origin", "HEAD:main");
  sh(A, "tag", "v1");
  sh(A, "switch", "-qc", "side"); const side = commit(A, "s.txt", "side\n", "Side work"); sh(A, "switch", "-q", "main");
  commit(A, "f.txt", "one\ntwo\n", "Fix the bug");
  sh(A, "merge", "-q", "--no-ff", "--no-edit", "side");
  sh(base, "clone", "-q", "remote.git", "b"); const B = join(base, "b"); cfg(B);
  commit(B, "g.txt", "from b\n", "Remote work"); sh(B, "push", "-q");
  sh(A, "fetch", "-q");
  const local = commit(A, "f.txt", "one\ntwo\nthree\n", "Local three");
  return { base, A, B, first, side, local };
}
const commitsList = (tree) => lists(tree).find((l) => l.listId === "history-commits");

test("the History page: commits, lanes, ↑ ↓, details, files and diff, search, All branches, reloading", async () => {
  const { A, first, side, local } = historyRepos();
  const view = await mount(A, { palette: "theme", view: "history" }), h = view.part.history;
  assert.equal(h.error, null, String(h.error)); assert.equal(h.root, A);
  assert.deepEqual(h.commits.map((c) => c.subject).sort(), ["First", "Fix the bug", "Local three", "Merge branch 'side'", "Remote work", "Side work"].sort());
  assert.ok(h.ahead.has(local) && h.ahead.size === 4); assert.equal(h.behind.size, 1);
  assert.equal(h.commits[0].subject, "Remote work", "not pulled: at the top");
  assert.equal(h.head.branch, "main"); assert.equal(h.head.upstream, "origin/main");
  assert.ok(h.graph && h.graph.length === h.commits.length);
  let tree = await draw(view);
  assert.ok(texts(byId(tree, "history")).includes("History"));
  let rows = renderRows(commitsList(tree));
  assert.deepEqual(state.violations, []);
  let paths = 0; for (const r of rows) walk(r, (n) => { if (n.kind === "path") paths++; });
  assert.ok(paths >= rows.length, "every row draws its lanes and dot");
  const rowTexts = rows.map((r) => texts(r).join(" "));
  assert.ok(rowTexts.some((x) => x.includes("↑") && x.includes("Local three")));
  assert.ok(rowTexts.some((x) => x.includes("↓") && x.includes("Remote work")));
  assert.ok(rowTexts.some((x) => x.includes("v1")));
  const merge = h.commits.find((c) => c.parents.length === 2);
  handler(commitsList(tree), "on_item_click")(merge.hash, makeCx()); await settle();
  assert.equal(h.selected, merge.hash); assert.equal(h.details.parents.length, 2);
  assert.deepEqual(h.files.map((f) => f.path), ["s.txt"]); assert.equal(h.file, "s.txt");
  const d = view.part.diff;
  assert.ok(d.rows.some((r) => r.kind === "+" && r.text === "side"));
  tree = await draw(view);
  assert.ok(texts(byId(tree, "history-info")).some((x) => /Parents:/.test(x)));
  const diffList = lists(tree).find((l) => l.listId === "history-diff");
  assert.ok(diffList && diffList.count > 0);
  const diffRows = renderRows(diffList);
  assert.ok(!diffRows.some((r) => texts(r).includes("Stage")), "read-only: no hunk buttons");
  assert.deepEqual(state.violations, []);
  handler(commitsList(tree), "on_item_click")(h.commits.find((c) => c.subject === "Local three").hash, makeCx()); await settle();
  assert.deepEqual(h.files.map((f) => [f.status, f.path, f.add, f.del]), [["M", "f.txt", 1, 0]]);
  handler(commitsList(tree), "on_item_click")(first, makeCx()); await settle();
  assert.deepEqual(h.details.parents, []); assert.ok(/^[0-9a-f]{40}$/.test(h.from));
  assert.ok(d.rows.some((r) => r.kind === "+" && r.text === "one"));
  assert.ok(texts(byId(await draw(view), "history-info")).some((x) => /Root commit/.test(x)));
  handler(commitsList(tree), "on_item_click")(merge.hash, makeCx()); await settle();
  press(byId(await draw(view), "history-parent-1")); await settle();
  assert.equal(h.selected, side);
  handler(commitsList(await draw(view)), "on_item_click")(side, makeCx()); await settle();
  assert.equal(h.selected, null, "a second click closes it");
  h.search.set_value("FIX THE"); await settle();
  assert.deepEqual(h.commits.map((c) => c.subject), ["Fix the bug"]); assert.equal(h.graph, null);
  renderRows(commitsList(await draw(view)));
  h.search.set_value(side.slice(0, 8)); await settle();
  assert.equal(h.commits[0].hash, side);
  h.search.set_value("author:nobody"); await settle();
  assert.equal(h.commits.length, 0);
  assert.ok(texts(byId(await draw(view), "history-list-area")).includes("No commit matches"));
  h.search.set_value("path:s.txt"); await settle();
  assert.deepEqual(h.commits.map((c) => c.subject), ["Side work"]);
  h.search.set_value(""); await settle();
  assert.equal(h.commits.length, 6);
  sh(A, "switch", "-qc", "lonely", first); commit(A, "l.txt", "l\n", "Lonely branch"); sh(A, "switch", "-q", "main");
  // The branch menu's All branches, then its Current branch.
  const branchMenu = async () => { let pop = null; walk(await draw(view), (n) => { if (n.popover === "history-branches") pop ??= n; }); handler(pop, "on_open_change")(true, makeCx()); return draw(view); };
  press(byId(await branchMenu(), "history-branch-all")); await settle();
  assert.equal(h.all, true); assert.ok(h.commits.some((c) => c.subject === "Lonely branch"));
  press(byId(await branchMenu(), "history-branch-head")); await settle();
  assert.ok(!h.commits.some((c) => c.subject === "Lonely branch"));
  commit(A, "f.txt", "one\ntwo\nthree\nfour\n", "Four");
  h.refresh(makeCx("async")); await settle();
  assert.equal(h.commits[1].subject, "Four");
  const logs = () => state.execLog.filter((e) => e[0] === "git" && e[1].includes("log") && e[1].includes("--topo-order")).length;
  const before = logs();
  h.refresh(makeCx("async")); await settle();
  assert.equal(logs(), before, "nothing moved: no new log");
  assert.deepEqual(state.violations, []);
});

test("the commit menu: a branch, a tag, a revert that stops (Abort), a cherry-pick, resets (hard asks twice), a checkout, Copy SHA", async () => {
  const { A, first } = historyRepos();
  sh(A, "switch", "-qc", "lonely", first); commit(A, "l.txt", "l\n", "Lonely branch"); sh(A, "switch", "-q", "main");
  const view = await mount(A, { palette: "theme", view: "history" }), h = view.part.history;
  handler(commitsList(await draw(view)), "on_item_secondary_click")(first, {}, makeCx());
  const menu = state.overlays.at(-1);
  assert.equal(menu.kind, "popup"); assert.equal(menu.props.commitMenu.sha, first);
  const open = async (props) => { const o = overlay({ props }); await settle(); return o; };
  let m = await open({ commitMenu: menu.props.commitMenu });
  let mt = drawWith(m.view, m.props);
  assert.ok(texts(mt).includes("Cherry-pick onto main…") && texts(mt).includes("Copy SHA"));
  assert.ok(!byId(mt, "commit-overlay").calls.some(([c]) => c === "overflow_y_scrollbar" || c === "overflow_y_scroll" || c === "size_full"), "a popup's root is no scroll area");
  state.props = m.props;
  press(byId(mt, "commit-branch"));
  const ask = state.overlays.at(-1);
  assert.equal(ask.props.commitName.action, "branch");
  let d = await open({ commitName: ask.props.commitName });
  state.props = d.props;
  d.view.part.input.set_value("bad..name"); d.view.part.go(makeCx()); await settle();
  assert.match(d.view.part.error, /can't be a branch name/);
  d.view.part.input.set_value("from-first"); d.view.part.go(makeCx()); await settle();
  assert.equal(sh(A, "rev-parse", "from-first").trim(), first);
  assert.ok(state.notes.at(-1).title.includes("Created branch from-first"));
  d = await open({ commitName: { ...ask.props.commitName, action: "tag" } });
  state.props = d.props;
  d.view.part.input.set_value("t-first"); d.view.part.go(makeCx()); await settle();
  assert.equal(sh(A, "rev-parse", "t-first").trim(), first);
  const bug = h.commits.find((c) => c.subject === "Fix the bug");
  const C = { ...menu.props.commitMenu, sha: bug.hash, short: bug.hash.slice(0, 7), subject: bug.subject, parents: bug.parents };
  d = await open({ commitAsk: { ...C, action: "revert", mode: null } });
  state.props = d.props; d.view.part.go(makeCx()); await settle();
  assert.ok(d.view.part.stopped, `stopped: ${d.view.part.error}`);
  assert.ok(existsSync(join(A, ".git", "REVERT_HEAD")));
  const dt = drawWith(d.view, d.props);
  assert.ok(texts(dt).some((x) => /stopped/.test(x)));
  // What git said, in a box that has the dialog's room left (the layout lint checks its column has a
  // height: in a body as tall as its content it came out 0 px tall).
  const said = byId(dt, "commit-stopped");
  assert.ok(texts(said).join(" ").includes(d.view.part.stopped.split("\n")[0].trim()), "git's words in it");
  assert.deepEqual(state.violations.filter((v) => /commit-stopped/.test(v)), []);
  h.refresh(makeCx("async")); await settle();
  assert.equal(h.op, "revert");
  state.props = { palette: "theme", view: "history" };
  assert.ok(byId(await draw(view), "history-abort"));
  state.props = d.props; press(byId(dt, "commit-abort")); await settle();
  assert.ok(!existsSync(join(A, ".git", "REVERT_HEAD")));
  const lonely = sh(A, "rev-parse", "lonely").trim();
  d = await open({ commitAsk: { ...C, sha: lonely, short: lonely.slice(0, 7), subject: "Lonely branch", parents: [first], action: "cherry-pick" } });
  state.props = d.props; d.view.part.go(makeCx()); await settle();
  assert.equal(d.view.part.error, null); assert.equal(sh(A, "log", "-1", "--format=%s").trim(), "Lonely branch");
  writeFileSync(join(A, "f.txt"), "dirty\n"); writeFileSync(join(A, "s.txt"), "dirty\n");
  const target = sh(A, "rev-parse", "HEAD~1").trim();
  d = await open({ commitAsk: { ...C, sha: target, short: target.slice(0, 7), action: "reset", mode: "hard" } });
  assert.ok(texts(drawWith(d.view, d.props)).some((x) => /2 files are lost/.test(x)));
  state.props = d.props; d.view.part.go(makeCx()); await settle();
  assert.notEqual(sh(A, "rev-parse", "HEAD").trim(), target, "the first press asks again");
  assert.ok(texts(drawWith(d.view, d.props)).includes("Really reset hard?"));
  state.props = d.props; d.view.part.go(makeCx()); await settle();
  assert.equal(sh(A, "rev-parse", "HEAD").trim(), target); assert.equal(sh(A, "status", "--porcelain").trim(), "");
  d = await open({ commitAsk: { ...C, sha: first, short: first.slice(0, 7), action: "reset", mode: "soft" } });
  state.props = d.props; d.view.part.go(makeCx()); await settle();
  assert.equal(sh(A, "rev-parse", "HEAD").trim(), first);
  assert.ok(sh(A, "diff", "--cached", "--stat").trim().length > 0);
  sh(A, "reset", "-q", "--hard", target);
  d = await open({ commitAsk: { ...C, sha: first, short: first.slice(0, 7), action: "checkout" } });
  state.props = d.props; d.view.part.go(makeCx()); await settle();
  assert.equal(sh(A, "rev-parse", "HEAD").trim(), first);
  sh(A, "switch", "-q", "main");
  m = await open({ commitMenu: menu.props.commitMenu });
  state.props = m.props;
  press(byId(drawWith(m.view, m.props), "commit-copy-sha"));
  assert.equal(state.notes.at(-1).title, "Copied the SHA"); assert.equal(state.clipboard.at(-1), first);
  state.props = { palette: "theme", view: "history" };
  assert.deepEqual(state.violations, []);
});

test("the History tab (wide, side by side), following the folder, not a repository, Load more, keys", async () => {
  const { base, A } = historyRepos();
  const view = await mount(A, { palette: "theme", view: "history" }), h = view.part.history;
  press(byId(await draw(view), "history-tab"));
  const tab = state.runs.at(-1);
  assert.equal(tab[0], "tab.new"); assert.deepEqual([tab[1].props.view, tab[1].props.root], ["history", A]);
  state.shared.set(KEY.layout, "split");
  const wide = await mount(join(base, "b"), { palette: "theme", view: "history", root: A, on: null }), wh = wide.part.history;
  assert.equal(wh.root, A, "the tab stays on its repository");
  let tree = await draw(wide);
  handler(byId(tree, "history"), "on_size_change")({ width: 1400, height: 900 }, makeCx());
  handler(commitsList(tree), "on_item_click")(wh.commits.find((c) => c.parents.length === 2).hash, makeCx()); await settle();
  assert.ok(wide.part.diff.sideBySide());
  tree = await draw(wide);
  assert.ok(byId(tree, "history-layout-split"));
  renderRows(lists(tree).find((l) => l.listId === "history-diff"));
  assert.ok(wide.part.diff.split?.length > 0);
  state.shared.delete(KEY.layout);
  state.props = { palette: "theme", view: "history" };
  at(join(base, "b"));
  assert.doesNotThrow(() => renderNow(view));
  await settle();
  assert.equal(h.root, join(base, "b"));
  const plain = join(base, "plain"); execFileSync("mkdir", ["-p", plain]);
  at(plain);
  assert.doesNotThrow(() => renderNow(view)); await settle();
  assert.equal(h.error, "Not a git repository");
  assert.ok(texts(byId(await draw(view), "history-list-area")).includes("Not a git repository"));
  const big = join(base, "big"); execFileSync("git", ["init", "-q", big]); cfg(big);
  let stream = "";
  for (let i = 1; i <= 650; i++) stream += `commit refs/heads/master\nmark :${i}\ncommitter T <t@x> ${1_600_000_000 + i} +0000\ndata ${String(i).length + 2}\nc ${i}\n${i > 1 ? `from :${i - 1}\n` : ""}M 644 inline f.txt\ndata ${String(i).length + 1}\n${i}\n\n`;
  execFileSync("git", ["fast-import", "--quiet"], { cwd: big, input: stream });
  sh(big, "reset", "-q", "--hard");
  at(big); renderNow(view); await settle();
  assert.equal(h.commits.length, 300); assert.equal(h.more, true);
  tree = await draw(view);
  assert.equal(commitsList(tree).count, 301);
  handler(commitsList(tree), "on_item_click")("more", makeCx()); await settle();
  assert.equal(h.commits.length, 600);
  h.loadMore(makeCx()); await settle();
  assert.equal(h.commits.length, 650); assert.equal(h.more, false);
  tree = await draw(view);
  const keys = handler(byId(tree, "history"), "on_key_down");
  keys({ key: "j", modifiers: {} }, makeCx()); await settle();
  assert.equal(h.selected, h.commits[0].hash);
  keys({ key: "down", modifiers: {} }, makeCx()); await settle();
  assert.equal(h.selected, h.commits[1].hash);
  assert.deepEqual(state.violations, []);
});

test("the search box and the filters: one row on a wide page, the search box on a row of its own on a narrow one", async () => {
  // In one row, a 370 px panel would leave the search box a few letters wide ("Messag").
  const { A } = historyRepos();
  const view = await mount(A, { palette: "theme", view: "history" }), h = view.part.history;
  const { FILTERS_IN_ONE_ROW } = await load("history.js");
  for (const width of [368, FILTERS_IN_ONE_ROW - 1, FILTERS_IN_ONE_ROW, 1300]) {
    h.size = { width, height: 800 };
    const bar = byId(await draw(view), "history-filters");
    assert.ok(bar, `the filter bar at ${width}`);
    const kids = bar.children.filter((c) => c?.$);
    if (width < FILTERS_IN_ONE_ROW) {
      assert.equal(kids.length, 2, `two rows at ${width}`);
      assert.ok(byId(kids[0], "history-search"), "the search box on the first row");
      assert.equal(byId(kids[0], "history-head"), null, "alone");
      assert.ok(byId(kids[1], "history-head") && byId(kids[1], "history-branch"), "the buttons on the second");
    } else {
      assert.ok(kids.some((k) => byId(k, "history-search")) && kids.some((k) => k.$.id === "history-head"), `one row at ${width}`);
      assert.ok(bar.calls.some(([m, a]) => m === "h" && a[0] === 38), "38 px, as before");
    }
  }
  assert.deepEqual(state.violations, []);
});
